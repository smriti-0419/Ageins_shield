import io
import zipfile
from pathlib import Path
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

LEVEL_COLORS = {"safe": "#10B981", "human": "#10B981", "moderate": "#F59E0B", "mixed": "#F59E0B",
                "danger": "#EF4444", "ai": "#EF4444"}
TYPE_TITLES = {"url": "Website Security Report", "ai": "AI Content Report", "email": "Phishing Email Report"}
SCORE_LABELS = {"url": "Security score (1-100)", "ai": "AI likelihood (%)", "email": "Phishing risk (%)"}


def build_pdf(scan: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm,
                            title=TYPE_TITLES[scan["type"]])
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], alignment=0, fontSize=20, textColor=colors.HexColor("#0F172A"))
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=colors.HexColor("#0E7490"))
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=9.5, leading=13)
    color = colors.HexColor(LEVEL_COLORS.get(scan["level"], "#64748B"))
    res = scan["result"]
    p = lambda t, s=body: Paragraph(escape(str(t)), s)

    story = [Paragraph("AgeinsShield", ParagraphStyle("brand", parent=body, textColor=colors.HexColor("#06B6D4"), fontSize=11)),
             Paragraph(TYPE_TITLES[scan["type"]], h1), Spacer(1, 4)]
    meta = [["Verdict", scan["verdict"]], [SCORE_LABELS[scan["type"]], str(scan["score"])],
            ["Scanned at", scan["created_at"][:19].replace("T", " ") + " UTC"], ["Report ID", scan.get("id", "")]]
    if scan["type"] == "url":
        meta.insert(0, ["URL", res.get("url", "")])
        age = res.get("domain_age") or {}
        if age.get("created"):
            meta.append(["Domain registered", f"{age['created']} ({age['age_days']} days ago)"])
        elif age.get("status") == "unregistered":
            meta.append(["Domain registered", "No registration record"])
    if scan["type"] == "email" and res.get("sender_domain"):
        meta.insert(0, ["Sender domain", res["sender_domain"]])
    t = Table([[p(a), p(b)] for a, b in meta], colWidths=[45 * mm, 125 * mm])
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F1F5F9")),
                           ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
                           ("TEXTCOLOR", (1, 0 if scan["type"] == "ai" else 0), (1, 0), colors.black),
                           ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story += [t, Spacer(1, 8),
              Paragraph(f'<font color="{color.hexval().replace("0x", "#")}"><b>{escape(scan["verdict"])}</b></font>', h2)]

    if scan["type"] in ("url", "email"):
        story.append(Paragraph("Findings", h2))
        flags = res.get("flags", [])
        if not flags:
            story.append(p("No red flags detected."))
        for f in flags:
            story.append(Paragraph(f"<b>[{escape(f['severity'].upper())}] {escape(f['title'])}</b> - {escape(f['detail'])}", body))
            story.append(Spacer(1, 3))
    else:
        m = res.get("metrics", {})
        story.append(Paragraph("Metrics", h2))
        story.append(p(f"Words: {m.get('words')} | Sentences: {m.get('sentences')} | Burstiness: {m.get('burstiness')} | "
                       f"Vocabulary richness: {m.get('vocabulary_richness')} | Perplexity index: {m.get('perplexity_index')}"))
        story.append(Paragraph("Signals", h2))
        for s in res.get("signals", []):
            story.append(p(f"- {s}"))
        story.append(Paragraph("Sentence scores", h2))
        for s in res.get("sentences", [])[:25]:
            story.append(p(f"{s['score']}%  {s['text']}"))
            story.append(Spacer(1, 2))

    story += [Spacer(1, 12), Paragraph("Generated by AgeinsShield rule-based analysis. Always verify critical decisions.",
                                       ParagraphStyle("f", parent=body, fontSize=8, textColor=colors.HexColor("#64748B")))]
    doc.build(story)
    return buf.getvalue()


def build_extension_zip(ext_dir: Path, api_base: str) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(ext_dir.rglob("*")):
            if f.is_dir():
                continue
            arc = f"aegisshield-extension/{f.relative_to(ext_dir).as_posix()}"
            if f.suffix in (".js", ".html", ".json"):
                z.writestr(arc, f.read_text().replace("__API_BASE__", api_base))
            else:
                z.write(f, arc)
    return buf.getvalue()
